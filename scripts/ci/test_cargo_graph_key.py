import cargo_graph_key

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
ZED = "git+https://github.com/zed-industries/zed?rev=cc053a4a#cc053a4a"
FLAKE = {"nodes": {"root": {"inputs": {"nixpkgs": "nixpkgs"}},
                   "nixpkgs": {"locked": {"type": "github", "rev": "a" * 40, "narHash": "sha256-x="}}},
         "root": "root", "version": 7}
# A workspace (app, core), a path dependency (maple-sdk), registry crates and a git crate.
PACKAGES = [
    {"name": "app", "version": "0.0.13", "dependencies": ["core", "gpui", "maple-sdk", "serde", "tokio"]},
    {"name": "core", "version": "0.0.13", "dependencies": ["serde"]},
    {"name": "gpui", "version": "0.2.2", "source": ZED, "dependencies": ["serde"]},
    {"name": "maple-sdk", "version": "4.1.3", "dependencies": ["serde", "tokio"]},
    {"name": "serde", "version": "1.0.228", "source": REGISTRY, "checksum": "a" * 64,
     "dependencies": ["serde_derive"]},
    {"name": "serde_derive", "version": "1.0.228", "source": REGISTRY, "checksum": "b" * 64},
    {"name": "tokio", "version": "1.48.0", "source": REGISTRY, "checksum": "c" * 64},
]


# What `cargo generate-lockfile` writes (file:// URLs replaced) when one name and version is
# locked from two git repositories: each reference carries its source without the `#<commit>`.
CARGO_GIT_PAIR = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "foo"
version = "0.1.0"
source = "git+https://example.com/repo-a{query_a}#{commit_a}"

[[package]]
name = "foo"
version = "0.1.0"
source = "git+https://example.com/repo-b{query_b}#{commit_b}"

[[package]]
name = "ws"
version = "{ws_version}"
dependencies = [
 "foo 0.1.0 (git+https://example.com/repo-a{query_a})",
 "foo 0.1.0 (git+https://example.com/repo-b{query_b})",
]
"""
COMMIT_A, COMMIT_B = "cccdf18898f6e4da7320c27d60a7c31d68dbdf0b", "df735244e8d17e671cb6218e5a5725c8ccb119f3"


def git_pair(rev=False, commit_a=COMMIT_A, ws_version="0.0.1"):
    """CARGO_GIT_PAIR on the default branch, or pinned by `rev =` in Cargo.toml."""
    return CARGO_GIT_PAIR.format(query_a=f"?rev={commit_a}" if rev else "", commit_a=commit_a,
                                 query_b=f"?rev={COMMIT_B}" if rev else "", commit_b=COMMIT_B,
                                 ws_version=ws_version)


def lock_text(packages, version=4):
    """A Cargo.lock as Cargo writes it."""
    lines = ["# This file is automatically @generated by Cargo.", "# It is not intended for manual editing.",
             f"version = {version}"]
    for package in packages:
        lines += ["", "[[package]]"]
        lines += [f'{field} = "{package[field]}"' for field in ("name", "version", "source", "checksum")
                  if field in package]
        if package.get("dependencies"):
            lines += ["dependencies = ["] + [f' "{name}",' for name in package["dependencies"]] + ["]"]
    return "\n".join(lines) + "\n"


def key(packages=PACKAGES, flake=FLAKE):
    return cargo_graph_key.key(lock_text(packages), json.dumps(flake, indent=2))


def edit(change):
    packages = copy.deepcopy(PACKAGES)
    change({package["name"]: package for package in packages})
    return packages


class LocalVersionTests(unittest.TestCase):
    def test_a_release_version_bump_keeps_the_key(self):
        def bump(by_name):
            by_name["app"]["version"] = by_name["core"]["version"] = "0.0.14"
        self.assertEqual(key(edit(bump)), key())

    def test_a_path_dependency_version_bump_keeps_the_key(self):
        self.assertEqual(key(edit(lambda by_name: by_name["maple-sdk"].update(version="4.2.0"))), key())

    def test_references_that_name_a_local_version_keep_the_key(self):
        # With a registry crate of the same name, Cargo writes the local version into references.
        def shadowed(local_version):
            def change(by_name):
                by_name["core"]["version"] = local_version
                by_name["app"]["dependencies"][0] = f"core {local_version}"
                by_name["serde"]["dependencies"].append("core 0.1.0")
            packages = edit(change)
            packages.append({"name": "core", "version": "0.1.0", "source": REGISTRY, "checksum": "d" * 64})
            return packages
        self.assertEqual(key(shadowed("0.0.14")), key(shadowed("0.0.13")))
        resolved = cargo_graph_key.graph(tomllib.loads(lock_text(shadowed("0.0.13"))))
        app = next(package for package in resolved["package"] if package["name"] == "app")
        self.assertIn(["core", "", ""], app["dependencies"])
        serde = next(package for package in resolved["package"] if package["name"] == "serde")
        self.assertIn(["core", "0.1.0", REGISTRY], serde["dependencies"])

    def test_a_path_dependency_moving_to_the_registry_changes_the_key(self):
        def published(by_name):
            by_name["maple-sdk"].update(source=REGISTRY, checksum="e" * 64)
        self.assertNotEqual(key(edit(published)), key())


class ThirdPartyTests(unittest.TestCase):
    def test_every_third_party_field_changes_the_key(self):
        for name, field, value in (("serde", "version", "1.0.229"), ("serde", "checksum", "f" * 64),
                                   ("serde_derive", "source", "registry+https://example.com/index"),
                                   ("gpui", "source", ZED.replace("cc053a4a", "0000000a")),
                                   ("tokio", "name", "tokio2")):
            with self.subTest(name=name, field=field):
                def change(by_name):
                    by_name[name][field] = value
                    if field == "name":  # and every reference to it
                        for package in by_name.values():
                            package["dependencies"] = [value if dependency == name else dependency
                                                       for dependency in package.get("dependencies", [])]
                self.assertNotEqual(key(edit(change)), key())

    def test_new_and_removed_dependency_edges_change_the_key(self):
        for owner, change in (
                ("core", lambda deps: deps.append("tokio")),    # a workspace crate's new edge
                ("serde_derive", lambda deps: deps.append("tokio")),  # a third-party edge
                ("app", lambda deps: deps.remove("serde")),
                ("maple-sdk", lambda deps: deps.remove("tokio"))):
            with self.subTest(owner=owner):
                packages = edit(lambda by_name: change(by_name[owner].setdefault("dependencies", [])))
                self.assertNotEqual(key(packages), key())

    def test_a_new_package_or_workspace_member_changes_the_key(self):
        for package in ({"name": "bytes", "version": "1.10.1", "source": REGISTRY, "checksum": "1" * 64},
                        {"name": "bench", "version": "0.0.13", "dependencies": ["core"]}):
            with self.subTest(name=package["name"]):
                self.assertNotEqual(key(PACKAGES + [package]), key())

    def test_a_source_qualified_reference_selects_its_source(self):
        # One name and version from two sources: Cargo writes the source, without a git
        # package's `#<commit>`, into references.
        fork = ZED.replace("zed-industries", "maple")

        def packages(source):
            reference = f"gpui 0.2.2 ({source.split('#')[0]})"
            result = edit(lambda by_name: by_name["app"]["dependencies"].__setitem__(1, reference))
            result.append({"name": "gpui", "version": "0.2.2", "source": fork})
            return result
        self.assertNotEqual(key(packages(ZED)), key(packages(fork)))

    def test_cargos_git_references_resolve_and_the_commit_still_counts(self):
        flake = json.dumps(FLAKE)
        for rev in (False, True):
            with self.subTest(rev=rev):
                resolved = cargo_graph_key.graph(tomllib.loads(git_pair(rev)))
                ws = next(package for package in resolved["package"] if package["name"] == "ws")
                self.assertEqual([dependency[2].rsplit("#", 1)[1] for dependency in ws["dependencies"]],
                                 [COMMIT_A, COMMIT_B])
                self.assertEqual(cargo_graph_key.key(git_pair(rev, ws_version="0.0.2"), flake),
                                 cargo_graph_key.key(git_pair(rev), flake))
                self.assertNotEqual(cargo_graph_key.key(git_pair(rev, commit_a="1" * 40), flake),
                                    cargo_graph_key.key(git_pair(rev), flake))

    def test_a_reference_without_a_source_names_the_local_package(self):
        # A local fork of a registry crate at the same version: Cargo writes no source
        # for the local one, and the registry source for the other.
        packages = edit(lambda by_name: by_name["app"]["dependencies"].__setitem__(3, "serde 1.0.228"))
        packages.append({"name": "serde", "version": "1.0.228", "dependencies": ["serde_derive"]})
        packages[1]["dependencies"] = [f"serde 1.0.228 ({REGISTRY})"]
        resolved = {(package["name"], package.get("source", "")): package["dependencies"]
                    for package in cargo_graph_key.graph(tomllib.loads(lock_text(packages)))["package"]}
        self.assertIn(["serde", "", ""], resolved[("app", "")])
        self.assertEqual(resolved[("core", "")], [["serde", "1.0.228", REGISTRY]])

    def test_the_lock_format_version_changes_the_key(self):
        self.assertNotEqual(cargo_graph_key.key(lock_text(PACKAGES, version=3), json.dumps(FLAKE)), key())


class ToolchainTests(unittest.TestCase):
    def test_a_flake_lock_change_changes_the_key(self):
        flake = copy.deepcopy(FLAKE)
        flake["nodes"]["nixpkgs"]["locked"]["rev"] = "b" * 40
        self.assertNotEqual(key(flake=flake), key())

    def test_toolchain_pins_join_the_key_only_when_given(self):
        pin = '{\n  "version": "27.1",\n  "build": "27A9275"\n}\n'
        lockfiles = (lock_text(PACKAGES), json.dumps(FLAKE, indent=2))
        self.assertEqual(cargo_graph_key.key(*lockfiles, ()), key())
        self.assertNotEqual(cargo_graph_key.key(*lockfiles, (pin,)), key())
        self.assertNotEqual(cargo_graph_key.key(*lockfiles, (pin.replace("27A9275", "27A9276"),)),
                            cargo_graph_key.key(*lockfiles, (pin,)))
        self.assertEqual(cargo_graph_key.key(*lockfiles, (pin.replace("\n", "\r\n"),)),
                         cargo_graph_key.key(*lockfiles, (pin,)))

    def test_formatting_order_and_line_endings_do_not_change_the_key(self):
        reordered = copy.deepcopy(PACKAGES[::-1])
        for package in reordered:
            package.get("dependencies", []).reverse()
        self.assertEqual(key(reordered), key())
        crlf = cargo_graph_key.key(lock_text(PACKAGES).replace("\n", "\r\n"),
                                   json.dumps(FLAKE, indent=4).replace("\n", "\r\n"))
        self.assertEqual(crlf, key())


class MalformedInputTests(unittest.TestCase):
    def assertRejected(self, cargo_lock, flake_lock=json.dumps(FLAKE)):
        with self.assertRaises(cargo_graph_key.GraphError):
            cargo_graph_key.key(cargo_lock, flake_lock)

    def test_unreadable_or_incomplete_locks_fail(self):
        self.assertRejected("[[package]\nname = 'x'\n")
        self.assertRejected("version = 4\n")
        self.assertRejected(lock_text(PACKAGES) + '\n[[package]]\nname = "orphan"\n')
        self.assertRejected(lock_text(PACKAGES) + '\n[[package]]\nname = "x"\nversion = ""\n')
        self.assertRejected(lock_text(PACKAGES) + '\n[[package]]\nname = "x"\nversion = "1"\ndependencies = "y"\n')
        self.assertRejected(lock_text(PACKAGES) + '\n[[package]]\nname = "x"\nversion = "1"\nbuilt = 1979-05-27\n')
        self.assertRejected(lock_text(PACKAGES), "{not json")
        self.assertRejected(lock_text(PACKAGES), "[]")

    def test_references_that_resolve_to_no_package_or_several_fail(self):
        for name, cases in (
                ("dangling", edit(lambda by_name: by_name["app"]["dependencies"].append("missing"))),
                ("wrong version", edit(lambda by_name: by_name["app"]["dependencies"].append("tokio 9.9.9"))),
                ("wrong source", edit(lambda by_name: by_name["app"]["dependencies"].append(
                    f"tokio 1.48.0 ({ZED})"))),
                ("unreadable", edit(lambda by_name: by_name["app"]["dependencies"].append("tokio 1.48.0 (")))):
            with self.subTest(name):
                self.assertRejected(lock_text(cases))
        # A bare name is ambiguous once two versions are locked, a local one included.
        for extra in ({"name": "tokio", "version": "0.2.0", "source": REGISTRY, "checksum": "2" * 64},
                      {"name": "core", "version": "0.1.0", "source": REGISTRY, "checksum": "2" * 64}):
            with self.subTest(extra=extra["name"]):
                self.assertRejected(lock_text(PACKAGES + [extra]))

    def test_packages_that_would_share_an_identity_fail(self):
        # Two local packages of one name are told apart only by the version this drops.
        self.assertRejected(lock_text(PACKAGES + [{"name": "bench", "version": "0.0.1"},
                                                  {"name": "bench", "version": "0.0.2"}]))
        twice = {"name": "bytes", "version": "1.10.1", "source": REGISTRY, "checksum": "1" * 64}
        self.assertRejected(lock_text(PACKAGES + [twice, dict(twice)]))

    def test_python_without_tomllib_fails_with_a_reason(self):
        with mock.patch.object(cargo_graph_key, "tomllib", None):
            with self.assertRaisesRegex(cargo_graph_key.GraphError, "3.11"):
                key()


class CommandLineTests(unittest.TestCase):
    def run_main(self, *argv):
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            code = cargo_graph_key.main(list(argv))
        return code, stdout.getvalue(), stderr.getvalue()

    def test_prints_one_github_output_line_for_the_agent_lockfiles(self):
        agent = ROOT / "apps/maple-agent"
        code, stdout, _ = self.run_main(str(agent / "Cargo.lock"), str(agent / "flake.lock"))
        self.assertEqual(code, 0)
        self.assertRegex(stdout, r"\Ahash=[0-9a-f]{64}\n\Z")

    def test_a_pin_file_argument_changes_the_agent_key(self):
        agent = ROOT / "apps/maple-agent"
        lockfiles = (str(agent / "Cargo.lock"), str(agent / "flake.lock"))
        _, plain, _ = self.run_main(*lockfiles)
        code, pinned, _ = self.run_main(*lockfiles, str(ROOT / "scripts/ci/apple-toolchain.json"))
        self.assertEqual(code, 0)
        self.assertRegex(pinned, r"\Ahash=[0-9a-f]{64}\n\Z")
        self.assertNotEqual(pinned, plain)

    def test_the_agent_lock_keeps_its_key_when_every_local_version_is_bumped(self):
        agent = ROOT / "apps/maple-agent"
        text, flake = (agent / "Cargo.lock").read_text(), (agent / "flake.lock").read_text()
        local = {package["name"] for package in tomllib.loads(text)["package"] if "source" not in package}
        self.assertTrue(local)
        bumped, count = re.subn(r'(?m)^(name = "(?:%s)"\nversion = ")[^"]+"$' % "|".join(map(re.escape, local)),
                                r'\g<1>99.0.0"', text)
        self.assertEqual(count, len(local))
        self.assertNotEqual(bumped, text)
        self.assertEqual(cargo_graph_key.key(bumped, flake), cargo_graph_key.key(text, flake))

    def test_failures_print_no_output_and_exit_non_zero(self):
        with tempfile.TemporaryDirectory() as directory:
            broken, flake = Path(directory) / "Cargo.lock", Path(directory) / "flake.lock"
            broken.write_text(lock_text(PACKAGES) + '\n[[package]]\nname = "orphan"\n')
            flake.write_text(json.dumps(FLAKE))
            for argv in ((str(broken), str(flake)), (str(broken),), (str(flake), str(Path(directory) / "none"))):
                with self.subTest(argv=argv):
                    code, stdout, stderr = self.run_main(*argv)
                    self.assertNotEqual(code, 0)
                    self.assertEqual(stdout, "")
                    self.assertTrue(stderr)


